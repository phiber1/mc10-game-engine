#!/usr/bin/env python3
"""sprview: lay out every sprite of a compiled sprite file for bench/view.asm.

    sprview.py NAME.spr build/view_spr.inc > build/view_list.inc
    sprview.py --defs NAME.spr      the cpp flags for the file's graphics
                                    mode (-DGFX_MODE=... -DGFX_BG=...)

Reads the sizes spritec wrote (the "; ---- sprite NAME: WxH" lines) and
emits code that draws each sprite once, at shift 0 (or the one shift a
"shift S" sprite has), left to right in rows, with its name underneath.
Public domain (Unlicense)."""
import re
import sys

BG = {'G': 0, 'W': 0, 'Y': 1, 'C': 1, 'B': 2, 'M': 2, 'R': 3, 'O': 3}


def file_mode(spr):
    """the first sprite's mode and (CG6) background color index"""
    m = re.search(r'^sprite\s+\w+\s+(\w+)(.*)$', open(spr).read(), re.M)
    if not m:
        return 'artifact', 0
    b = re.search(r'\bbg\s+(\S)', m.group(2))
    return m.group(1), (BG.get(b.group(1), 0) if b and m.group(1) == 'cg6' else 0)


if sys.argv[1] == '--defs':
    mode, bg = file_mode(sys.argv[2])
    print('-DGFX_MODE=GFX_CG6 -DGFX_BG=%d' % bg if mode == 'cg6' else '')
    sys.exit(0)

spr, inc = sys.argv[1], sys.argv[2]
text = open(inc).read()
sprites = []
for m in re.finditer(r'^; ---- sprite (\w+): (\d+)x(\d+) (\w+)', text, re.M):
    name, w, h, mode = m.group(1), int(m.group(2)), int(m.group(3)), m.group(4)
    table = name + ('_hr' if re.search(r'^%s_hr:' % name, text, re.M) else '_or')
    nbytes = (w * (2 if mode in ('artifact', 'cg6') else 1) + 7) // 8 + 1   # + a shift's spill
    sprites.append((name, w, h, table, nbytes, mode))

# the text color: white in RG6; in CG6 a color that isn't the background
mode, bg = file_mode(spr)

ROW_BYTES, TOP, BOTTOM = 32, 10, 192
out = ['; generated by tools/sprview.py from %s: do not edit' % spr]
out.append('vw_text\tequ\t%s' % ('$%02X' % ((bg ^ 1) * 0x55) if mode == 'cg6' else '$FF'))   # (TXT_WHITE: defined later)
title = spr.split('/')[-1].upper()[:30]
out.append('\tldx\t#SCREEN+1*ROW_BYTES+1')
out.append('\tldd\t#vw_title')
out.append('\tjsr\ttxt_str')
strings = ['vw_title:\tfcc\t"%s"\n\tfcb\t0' % re.sub(r'[^A-Z0-9 ./_-]', '', title)]
col, row, rowh, shown = 1, TOP, 0, 0
for name, w, h, table, nb, _ in sprites:
    label = name.upper()[:31]
    width = max(nb, len(label))
    if col + width > ROW_BYTES:                     # next row
        col, row, rowh = 1, row + rowh, 0
    if width > ROW_BYTES or row + h + 7 > BOTTOM:
        out.append('; %s: no room left on the screen' % name)
        continue
    out.append('; %s %dx%d' % (name, w, h))
    out.append('\tldx\t#%s' % table)
    out.append('\tldx\t0,x')
    out.append('\tstx\tvw_rt')
    out.append('\tldx\t#SCREEN+%d*ROW_BYTES+%d' % (row, col))
    out.append('\tjsr\tvw_call')
    out.append('\tldx\t#SCREEN+%d*ROW_BYTES+%d' % (row + h + 1, col))
    out.append('\tldd\t#vw_s%d' % shown)
    out.append('\tjsr\ttxt_str')
    strings.append('vw_s%d:\tfcc\t"%s"\n\tfcb\t0' % (shown, re.sub(r'[^A-Z0-9 ./_-]', '', label)))
    shown += 1
    col += width + 1
    rowh = max(rowh, h + 8)
out.append('\tjmp\tvw_done')
out += strings
out.append('vw_done:')
print('\n'.join(out))
print('sprview: %d of %d sprites placed' % (shown, len(sprites)), file=sys.stderr)
